//! `authz init`: draft a policy for a server from its real tool list.
//!
//! The server's names, arguments and annotations only *suggest* a risk class. When unsure,
//! the draft fails safe: unclassifiable or destructive tools start refused, with a comment
//! saying so. The output is a starting point for review, not a finished policy.

use std::fmt::Write as _;

use authz_core::{Hints, ToolSpec};

const EXEC: &[&str] =
    &["exec", "execute", "run", "shell", "command", "cmd", "terminal", "eval", "script", "spawn"];
const EGRESS: &[&str] = &[
    "fetch", "http", "request", "url", "send", "email", "mail", "post", "upload", "publish",
    "webhook", "notify", "message", "browse", "navigate",
];
const WRITE: &[&str] = &[
    "write", "edit", "create", "delete", "remove", "move", "rename", "update", "set", "put",
    "commit", "push", "reset", "add", "append", "insert", "drop", "merge", "checkout", "init",
    "apply", "patch", "upsert", "destroy", "kill", "stop",
];
const READ: &[&str] = &[
    "read", "get", "list", "search", "find", "show", "status", "diff", "log", "tree", "info",
    "query", "describe", "view", "inspect", "count", "head", "tail", "stat",
];
const URL_ARGS: &[&str] = &["url", "uri", "endpoint", "link", "href"];
const TO_ARGS: &[&str] = &["to", "recipient", "recipients", "email", "cc", "bcc"];
const CMD_ARGS: &[&str] = &["cmd", "command", "script"];

/// `readMultipleFiles`, `read_multiple-files` -> ["read", "multiple", "files"].
fn words(name: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut prev_lower = false;
    for c in name.chars() {
        let boundary = !c.is_ascii_alphanumeric() || (c.is_ascii_uppercase() && prev_lower);
        if boundary && !cur.is_empty() {
            out.push(std::mem::take(&mut cur));
        }
        if c.is_ascii_alphanumeric() {
            cur.push(c.to_ascii_lowercase());
        }
        prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

fn args(spec: &ToolSpec) -> Vec<String> {
    spec.schema["properties"].as_object().map(|o| o.keys().cloned().collect()).unwrap_or_default()
}

fn first<'a>(have: &'a [String], want: &[&str]) -> Option<&'a str> {
    have.iter().find(|a| want.contains(&a.to_lowercase().as_str())).map(String::as_str)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Guess {
    Read,
    Write,
    Egress,
    Exec,
    Unknown,
}

pub fn classify(spec: &ToolSpec, h: &Hints) -> Guess {
    let w = words(&spec.name);
    let a = args(spec);
    let has = |set: &[&str]| w.iter().any(|x| set.contains(&x.as_str()));
    if first(&a, CMD_ARGS).is_some() || has(EXEC) {
        Guess::Exec
    } else if first(&a, URL_ARGS).is_some() || first(&a, TO_ARGS).is_some() || has(EGRESS) {
        Guess::Egress
    } else if has(WRITE) || (!h.read_only && !has(READ)) {
        if has(WRITE) || h.destructive { Guess::Write } else { Guess::Unknown }
    } else if has(READ) || h.read_only {
        Guess::Read
    } else {
        Guess::Unknown
    }
}

/// YAML key for a tool name: bare when safe, otherwise a JSON string (valid YAML).
fn key(name: &str) -> String {
    if name.chars().all(|c| c.is_ascii_alphanumeric() || "_-.".contains(c)) {
        name.into()
    } else {
        serde_json::to_string(name).unwrap_or_default()
    }
}

const PATTERNS: &str = r#"patterns:
  secret:
    - 'sk-(live|test|proj)-[A-Za-z0-9_-]{8,}'
    - 'AKIA[0-9A-Z]{16}'
    - '(?i)aws_secret_access_key'
    - 'gh[pousr]_[A-Za-z0-9]{20,}'
    - '-----BEGIN [A-Z ]*PRIVATE KEY-----'
  sensitive_path:
    - '(^|[\\/])\.env(\.[^\\/]*)?$'
    - '\.(pem|key|p12|pfx)$'
    - '(^|[\\/])id_(rsa|ed25519|ecdsa)'
    - '(^|[\\/])\.ssh([\\/]|$)'
    - '(^|[\\/])\.aws[\\/]credentials$'
    - '(^|[\\/])\.(npmrc|pypirc|netrc)$'
  runs_later:
    - '(^|[\\/])\.git[\\/]hooks([\\/]|$)'
    - '(^|[\\/])\.github[\\/]workflows([\\/]|$)'
    - '(^|[\\/])\.husky([\\/]|$)'
    - '(^|[\\/])\.vscode[\\/](tasks|launch|settings)\.json$'
    - '(^|[\\/])\.(bashrc|zshrc|profile|bash_profile)$'
"#;

pub fn draft(server: &str, tools: &[(ToolSpec, Hints)]) -> String {
    let guessed: Vec<_> = tools.iter().map(|(s, h)| (s, h, classify(s, h))).collect();
    let any = |g: Guess| guessed.iter().any(|(_, _, x)| *x == g);
    let mut y = String::new();
    let _ = writeln!(y, "# Draft policy for: {server}");
    let _ = writeln!(
        y,
        "# Generated by `authz init` from the server's own tool list. REVIEW BEFORE USE:"
    );
    let _ = writeln!(
        y,
        "# classes are guesses from names, arguments and the server's (untrusted) hints."
    );
    let _ = writeln!(y, "default: deny\n");
    let _ = writeln!(y, "# Destinations you trust. Anything not listed is refused.");
    let _ = writeln!(y, "allow:\n  hosts: []\n  emails: []\n  commands: []\n");
    let _ = writeln!(y, "tools:");
    for (s, h, g) in &guessed {
        let (action, class, note) = match g {
            Guess::Read => ("allow", "read", ""),
            Guess::Write if h.destructive => {
                ("escalate", "write", "  # destructive per the server: refused until you allow it")
            }
            Guess::Write => ("allow", "write", ""),
            Guess::Egress => ("allow", "egress", ""),
            Guess::Exec => ("allow", "exec", "  # only commands in allow.commands run"),
            Guess::Unknown => {
                ("escalate", "write", "  # couldn't classify: refused until you review it")
            }
        };
        let taint = if *g == Guess::Read { ", taint: private" } else { "" };
        let _ =
            writeln!(y, "  {}: {{action: {action}, class: {class}{taint}}}{note}", key(&s.name));
    }
    let _ = writeln!(y);
    y += PATTERNS;
    let _ = writeln!(y, "\nrules:");
    let rule = |y: &mut String, id: &str, act: &str, sel: &str, when: &str| {
        let _ = writeln!(y, "  - id: {id}\n    action: {act}\n    {sel}\n    when: [{when}]\n");
    };
    if any(Guess::Read) {
        rule(
            &mut y,
            "sensitive-read",
            "deny",
            "class: read",
            "{any_arg_matches: {set: sensitive_path}}",
        );
        rule(&mut y, "hint-disagrees", "escalate", "class: read", "{hint: destructive}");
    }
    if any(Guess::Write) || any(Guess::Unknown) {
        rule(&mut y, "secret-write", "deny", "class: write", "{any_arg_matches: {set: secret}}");
        rule(
            &mut y,
            "runs-later-write",
            "deny",
            "class: write",
            "{any_arg_matches: {set: runs_later}}",
        );
        rule(
            &mut y,
            "sensitive-write",
            "deny",
            "class: write",
            "{any_arg_matches: {set: sensitive_path}}",
        );
    }
    if any(Guess::Egress) {
        rule(&mut y, "secret-egress", "deny", "class: egress", "{any_arg_matches: {set: secret}}");
    }
    for (s, _, g) in &guessed {
        let a = args(s);
        let t = key(&s.name);
        if *g == Guess::Egress {
            if let Some(u) = first(&a, URL_ARGS) {
                let w = format!("{{arg_not_in_task: {{arg: {u}, kind: host}}}}");
                rule(
                    &mut y,
                    &format!("unlisted-host-{}", s.name),
                    "deny",
                    &format!("tool: {t}"),
                    &w,
                );
                if any(Guess::Read) {
                    let w = format!(
                        "{{carries_taint: {{label: private, min: 8, args: [{u}]}}}}, {{arg_not_in_task: {{arg: {u}, kind: host}}}}"
                    );
                    rule(&mut y, &format!("tainted-{}", s.name), "deny", &format!("tool: {t}"), &w);
                }
            }
            if let Some(r) = first(&a, TO_ARGS) {
                let w = format!("{{arg_not_in_task: {{arg: {r}, kind: email}}}}");
                rule(
                    &mut y,
                    &format!("unlisted-recipient-{}", s.name),
                    "deny",
                    &format!("tool: {t}"),
                    &w,
                );
            }
        }
        if *g == Guess::Exec {
            if let Some(c) = first(&a, CMD_ARGS) {
                let w = format!("{{arg_not_in_task: {{arg: {c}, kind: literal}}}}");
                rule(
                    &mut y,
                    &format!("unlisted-command-{}", s.name),
                    "deny",
                    &format!("tool: {t}"),
                    &w,
                );
            } else {
                rule(&mut y, &format!("review-{}", s.name), "escalate", &format!("tool: {t}"), "");
            }
        }
    }
    y
}

#[cfg(test)]
mod tests {
    use authz_guard::Rules;
    use serde_json::json;

    use super::*;

    fn tool(name: &str, args: &[&str], ro: bool, destructive: bool) -> (ToolSpec, Hints) {
        let props: serde_json::Map<_, _> =
            args.iter().map(|a| (a.to_string(), json!({"type": "string"}))).collect();
        let spec = ToolSpec {
            name: name.into(),
            description: String::new(),
            schema: json!({"type": "object", "properties": props}),
        };
        (spec, Hints { read_only: ro, destructive, open_world: false })
    }

    #[test]
    fn splits_names_into_words() {
        assert_eq!(words("readMultipleFiles"), ["read", "multiple", "files"]);
        assert_eq!(words("git_diff-unstaged"), ["git", "diff", "unstaged"]);
        assert!(!words("get_address").contains(&"add".to_string()), "no substring matches");
    }

    #[test]
    fn classifies_and_drafts_a_policy_that_loads() {
        let tools = [
            tool("read_text_file", &["path"], true, false),
            tool("write_file", &["path", "content"], false, true),
            tool("fetch", &["url"], true, false),
            tool("send_email", &["to", "body"], false, false),
            tool("run_command", &["command"], false, true),
            tool("frobnicate", &["x"], false, false),
        ];
        let got: Vec<_> = tools.iter().map(|(s, h)| classify(s, h)).collect();
        use Guess::*;
        assert_eq!(got, [Read, Write, Egress, Egress, Exec, Unknown]);
        let y = draft("test-server", &tools);
        let r = Rules::parse(&y).unwrap_or_else(|e| panic!("draft must load: {e}\n{y}"));
        assert!(r.rule_ids().contains(&"unlisted-host-fetch"));
        assert!(r.rule_ids().contains(&"tainted-fetch"));
        assert!(r.rule_ids().contains(&"unlisted-recipient-send_email"));
        assert!(r.rule_ids().contains(&"unlisted-command-run_command"));
        assert!(y.contains("write_file: {action: escalate"), "destructive starts refused");
        assert!(y.contains("frobnicate: {action: escalate"), "unknown starts refused");
    }
}
